import Crypto
import DriverrCore
import Foundation
import Testing
@testable import DriverrSSH

/// Runs the real `ssh-keygen`, because our writer against our parser proves only
/// self-consistency. Generating at test time keeps private keys out of the repository.
enum SSHKeygen {
  static var isAvailable: Bool {
    FileManager.default.isExecutableFile(atPath: "/usr/bin/ssh-keygen")
  }

  /// Returns the PEM private key and the `.pub` line ssh-keygen wrote beside it.
  static func generateEd25519(
    comment: String,
    passphrase: String = ""
  ) throws -> (privatePEM: String, publicLine: String) {
    let directory = URL(fileURLWithPath: NSTemporaryDirectory())
      .appendingPathComponent("driverr-keytest-\(UUID().uuidString)")
    try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
    defer { try? FileManager.default.removeItem(at: directory) }

    let keyPath = directory.appendingPathComponent("id_ed25519")
    let process = Process()
    process.executableURL = URL(fileURLWithPath: "/usr/bin/ssh-keygen")
    process.arguments = [
      "-t", "ed25519", "-N", passphrase, "-C", comment, "-f", keyPath.path,
    ]
    process.standardOutput = FileHandle.nullDevice
    process.standardError = FileHandle.nullDevice
    try process.run()
    process.waitUntilExit()

    let pem = try String(contentsOf: keyPath, encoding: .utf8)
    let pub = try String(
      contentsOf: keyPath.appendingPathExtension("pub"),
      encoding: .utf8
    )
    return (pem, pub.trimmingCharacters(in: .whitespacesAndNewlines))
  }
}

@Suite("OpenSSHPrivateKey", .enabled(if: SSHKeygen.isAvailable))
struct OpenSSHPrivateKeyTests {
  @Test("parses a key generated by ssh-keygen and derives the same public key")
  func parsesRealKeyAndDerivesPublicKey() throws {
    let generated = try SSHKeygen.generateEd25519(comment: "carson@driverr")
    let parsed = try OpenSSHPrivateKey.parse(pem: generated.privatePEM)

    // ssh-keygen's .pub line is the ground truth for the public half.
    let expectedBlob = generated.publicLine.split(separator: " ")[1]
    #expect(parsed.publicKeyBase64 == String(expectedBlob))
  }

  @Test("the parsed private key is the one that matches that public key")
  func parsedPrivateKeyMatchesPublicKey() throws {
    let generated = try SSHKeygen.generateEd25519(comment: "carson@driverr")
    let parsed = try OpenSSHPrivateKey.parse(pem: generated.privatePEM)

    // The OpenSSH field is seed||public, 64 bytes; a wrong split would change this.
    let signingKey = try Curve25519.Signing.PrivateKey(
      rawRepresentation: parsed.privateKey.rawRepresentation
    )
    #expect(signingKey.publicKey.rawRepresentation == parsed.publicKeyRaw)
  }

  @Test("keeps the comment ssh-keygen embedded in the key")
  func preservesComment() throws {
    let generated = try SSHKeygen.generateEd25519(comment: "carson@driverr")
    let parsed = try OpenSSHPrivateKey.parse(pem: generated.privatePEM)
    #expect(parsed.comment == "carson@driverr")
  }

  @Test("a passphrase-protected key is refused with a message that says what to do")
  func encryptedKeyIsRefused() throws {
    // A real encrypted file proves the parser reaches the passphrase check rather than failing
    // on the body first.
    let generated = try SSHKeygen.generateEd25519(
      comment: "carson@driverr",
      passphrase: "any passphrase at all"
    )

    do {
      _ = try OpenSSHPrivateKey.parse(pem: generated.privatePEM)
      Issue.record("an encrypted key should not parse")
    } catch let error as AppError {
      #expect(error.errorDescription?.lowercased().contains("passphrase") == true)
    }
  }

  @Test("a PEM that is not an OpenSSH key is refused")
  func garbageIsRefused() {
    #expect(throws: AppError.self) {
      try OpenSSHPrivateKey.parse(pem: "not a key at all")
    }
  }

  @Test("an RSA key is refused, naming Ed25519 as what is supported")
  func rsaKeyIsRefused() {
    let pem = """
      -----BEGIN RSA PRIVATE KEY-----
      \(Data("nonsense".utf8).base64EncodedString())
      -----END RSA PRIVATE KEY-----
      """
    #expect(throws: AppError.self) {
      try OpenSSHPrivateKey.parse(pem: pem)
    }
  }
}
